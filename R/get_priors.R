#' Priors for a \pkg{bayesnec} model
#'
#' Returns priors in the form \code{\link{bnec}} accepts them, either from a fit
#' that has already been run or from a formula and data before anything is
#' fitted.
#'
#' @param object An object of class \code{\link{bayesnecfit}},
#' \code{\link{bayesmanecfit}} or \code{\link{bayesnechurdlefit}} as returned by
#' \code{\link{bnec}}; or a \code{\link{bayesnecformula}}, a
#' \code{\link[stats]{formula}} or a \code{\link[base]{character}} string that
#' can be coerced to one.
#' @param ... Unused.
#'
#' @details Two entry points, answering two different questions.
#'
#' \bold{Given a fit,} \code{get_priors} returns the priors that fit actually
#' used, including any the user overrode. This is the record of what was run:
#' \code{bnec(formula, data = data, prior = get_priors(fit))} reproduces the same
#' model.
#'
#' \bold{Given a formula and data,} it returns the priors \code{\link{bnec}}
#' would generate, without fitting anything, so they can be inspected and edited
#' before the first run. The family is chosen from the data exactly as
#' \code{\link{bnec}} would unless one is supplied, and models invalid for it are
#' dropped with the same message.
#'
#' The two can disagree, and that is the point of having both: once a prior has
#' been overridden, the fit's priors are no longer the ones the defaults would
#' produce. Given the same formula, data and family, and no user prior, they
#' agree.
#'
#' What is returned is the population-level priors on the parameters of the
#' model's own non-linear formula, which are the ones \code{\link{bnec}} accepts
#' through \code{prior}. Where a \code{disp} term adds a variance function on the
#' fitted mean -- \code{disp("power")} and the other named forms -- its
#' parameters (\code{c0}, \code{c1}, ...) belong to that formula and come back
#' with the curve parameters. They are needed: \code{\link{bnec}} takes a
#' supplied prior whole, so a set handed back without them leaves \pkg{brms} to
#' put a flat prior on each, which is a different model. See
#' \code{\link{bayesnecformula}}.
#'
#' What is left to \pkg{brms} and its defaults, and so is not returned, is the
#' family's own dispersion parameter (\code{sigma}, \code{shape}, \code{phi})
#' where dispersion is held constant, and the linear predictor of a
#' \code{disp(~x)} sub-model. Neither can be supplied through
#' \code{bnec(prior = )} in any case, because the initial-value search matches
#' prior names against the model's own parameters and rejects any prior naming
#' one outside that set.
#'
#' This is why \code{get_priors} is not \code{\link{pull_prior}}, which returns
#' the whole \code{brmsprior} a fit carries -- \pkg{brms} defaults, duplicated
#' vectorized rows and all -- and is for looking at rather than for feeding back
#' in.
#'
#' The returned priors are specific to a formula generated by \code{bnec()}.
#' Each non-linear parameter in that formula has one population-level
#' coefficient, its intercept, so a prior naming the parameter and no
#' coefficient applies to that scalar. After extending a parameter's
#' right-hand side in a formula passed directly to \code{\link[brms]{brm}},
#' check whether the added coefficients have the same meaning and support. For
#' example, after changing \code{top ~ 1} to \code{top ~ treatment}, the same
#' prior applies to both the intercept and the treatment contrasts, although a
#' contrast need not have the support of \code{top}. A no-intercept cell-means
#' formula such as \code{top ~ 0 + treatment} instead gives every coefficient
#' the meaning and support of a treatment-specific \code{top}, so a shared
#' parameter-level prior can be appropriate.
#'
#' Use \code{\link[brms]{get_prior}} to inspect the target coefficients. Where
#' their meaning or support differs, rebuild the priors under the
#' parameterisation used by that formula rather than reusing this object
#' unchanged. Adding \code{coef = "Intercept"} is not a general conversion:
#' \pkg{brms} does not allow \code{coef} together with \code{lb} or
#' \code{ub}, and those bounds are part of the priors \code{bayesnec}
#' generates for several parameters.
#'
#' @return For a single model, an object of class
#' \code{\link[brms]{brmsprior}}. For a model set, a named
#' \code{\link[base]{list}} of them, one per model, named as
#' \code{\link{bnec}} expects a named prior list to be. For a
#' \code{\link{bayesnechurdlefit}}, a \code{\link[base]{list}} of two such
#' objects, one per component.
#'
#' @seealso \code{\link{bnec}}, \code{\link{pull_prior}},
#' \code{\link{check_priors}}, \code{\link{show_params}}
#'
#' @examples
#' library(bayesnec)
#' data(manec_example)
#' # the priors a fit used, ready to pass back to bnec(prior = )
#' get_priors(manec_example)
#' # the priors bayesnec would generate, without fitting anything
#' get_priors(y ~ crf(x, "nec3param"), data = nec_data)
#'
#' @export
get_priors <- function(object, ...) {
  UseMethod("get_priors")
}

#' @noRd
#' @export
get_priors.default <- function(object, ...) {
  stop("get_priors() takes an object fitted by bnec, or a formula and data.",
       " You supplied an object of class \"", class(object)[1], "\".",
       call. = FALSE)
}

#' @noRd
#' @export
get_priors.bayesnecfit <- function(object, ...) {
  usable_prior(object$fit$prior)
}

#' @noRd
#' @export
get_priors.bayesmanecfit <- function(object, ...) {
  lapply(object$mod_fits, function(x) usable_prior(x$fit$prior))
}

#' @noRd
#' @export
get_priors.bayesnechurdlefit <- function(object, ...) {
  # Two separate fits with two separate model sets, so two sets of priors; there
  # is no single prior object that would reproduce the pair.
  list(growth = get_priors(object$growth),
       survival = get_priors(object$survival))
}

#' @rdname get_priors
#'
#' @param data A \code{\link[base]{data.frame}} containing the data referred to
#' by the formula.
#' @param family A \code{\link[stats]{family}} function, as passed to
#' \code{\link{bnec}}. If \code{NULL} (the default) it is chosen from the data
#' the way \code{\link{bnec}} would.
#' @param prior_type A \code{\link[base]{character}} string, either
#' \code{"uninformative"} (the default) or \code{"regularizing"}. See
#' \code{\link{bnec}}.
#' @param asymptote_observed A \code{\link[base]{logical}} declaring whether
#' the highest predictor level reached the lower asymptote of the curve.
#' \code{FALSE} replaces the \code{bot} entry, which is how the entries a fit
#' under that declaration would use can be read without fitting. See
#' \code{\link{bnec}}.
#' @param predictor_scale A \code{\link[base]{character}} string declaring
#' whether the predictor is supplied as \code{"concentration"}, already
#' \code{"log"} transformed, or should use the existing \code{"auto"} rule.
#' See \code{\link{bnec}}.
#' @param model_survival An optional \code{\link[base]{character}} string naming
#' the equation for the second block of a joint hurdle or zero-inflated fit. See
#' \code{\link{bnec}}.
#'
#' @inherit get_priors return details examples
#'
#' @method get_priors formula
#'
#' @importFrom stats model.frame
#' @importFrom chk chk_flag
#'
#' @export
get_priors.formula <- function(object, data, family = NULL,
                               prior_type = "uninformative",
                               asymptote_observed = TRUE,
                               model_survival = NULL,
                               predictor_scale = "auto", ...) {
  # A bayesnecformula has class c("formula", "bayesnecformula"), so dispatch
  # reaches this method for both. The bayesnecformula method forwards here;
  # forwarding the other way would recurse.
  object <- bayesnecformula(object, env = parent.frame())
  if (missing(data)) {
    stop("Argument `data` is required when get_priors() is given a formula:",
         " every default prior is derived from the data. See ?get_priors.",
         call. = FALSE)
  }
  prior_type <- match.arg(prior_type, c("uninformative", "regularizing"))
  chk_flag(asymptote_observed)
  predictor_scale <- validate_predictor_scale(predictor_scale)
  bdat <- model.frame(object, data = data, run_par_checks = TRUE)
  # Check for missing values immediately after the model frame, as bnec()
  # does, so that no check below reads a frame with rows already dropped.
  check_complete_cases(bdat)
  validate_predictor_scale(
    predictor_scale, retrieve_var(bdat, "x_var", error = TRUE)
  )
  # Read from `data`, as bnec() does: the variables of a disp(~...) term are
  # not in the model frame.
  check_disp_finite(object, data)
  # Run the sequence bnec() runs, through the same functions, so that the
  # priors returned are the priors bnec() would fit.
  link_source <- family_link_source(substitute(family), env = parent.frame())
  fam_args <- if (is.null(family)) list() else list(family = family)
  family <- retrieve_valid_family(fam_args, bdat, link_source = link_source)
  # Refuse a missing trials() term here, once, as bnec() does, before the
  # bound check and the substitution report read the response.
  check_trials_term(bdat, family)
  # Refuse a response at a bound once, before the substitution report below.
  # A curve equation has no prior on such a response, so a set holding one is
  # refused; ecxflat named alone is allowed. Unlike bnec(), this does not
  # substitute ecxflat for the set.
  requested <- get_model_from_formula(object)
  check_response_at_bound(bdat, family, model = requested)
  model <- check_models(requested, family, bdat)
  model_survival <- check_model_survival(model_survival, family, bdat)
  if (length(model) == 0) {
    stop("No valid models have been supplied for this data type.",
         call. = FALSE)
  }
  # Report substitutions once, here: check_data() below runs once per model
  # and does not report them. The priors are built from the substituted
  # response, so the user must be told it differs from the data supplied.
  report_substitutions(
    substitution_record(retrieve_var(bdat, "y_var", error = TRUE),
                        retrieve_cens(bdat), family),
    on_fit = FALSE
  )
  disp_spec <- parse_disp_term(object)
  # The disp() checks bnec() makes before its model loop, in the same order and
  # on the same response, so a term bnec() refuses gets the same message here.
  if (!is.null(disp_spec)) {
    check_disp_spec(disp_spec, family, response = disp_response(bdat, family))
    if (shape_in_reported_mean(object, family)) {
      check_disp_count_truncation(object, family)
    }
  }
  out <- lapply(model, function(m) {
    single_form <- single_model_formula(object, m)
    m_dat <- model.frame(single_form, data = data, run_par_checks = TRUE)
    # Run check_data() as fit_bayesnec() does: it can shift the response the
    # prior is built from, for instance moving zeros off a bound.
    checked <- check_data(data = m_dat, family = family, model = m)
    y <- checked$mod_dat$y
    if (checked$family$family %in% c("binomial", "beta_binomial")) {
      y <- y / checked$mod_dat$trials
    }
    # Divide by a rate() denominator as well: top and bot are on the rate
    # scale, and a prior built from raw counts is misplaced without warning.
    if (!is.null(checked$mod_dat$denom)) {
      y <- y / checked$mod_dat$denom
    }
    define_prior(m, checked$family, checked$mod_dat$x, y,
                 prior_type = prior_type,
                 asymptote_observed = asymptote_observed,
                 model_survival = model_survival,
                 predictor_scale = predictor_scale,
                 disp_spec = disp_spec,
                 group_spec = parse_group_terms(single_form, m),
                 rate_response = !is.null(checked$mod_dat$denom),
                 truncated_response = isTRUE(attr(
                   single_form, "bayesnec_internal_truncation")))
  })
  names(out) <- model
  if (length(out) == 1) {
    out[[1]]
  } else {
    out
  }
}

#' @noRd
#' @export
get_priors.bayesnecformula <- function(object, data, ...) {
  get_priors.formula(object, data = data, ...)
}

#' @noRd
#' @export
get_priors.character <- function(object, data, ...) {
  get_priors.formula(bayesnecformula(object, env = parent.frame()),
                     data = data, ...)
}

#' Reduce a fitted brmsprior to the rows bnec() will accept back
#'
#' @param prior The \code{\link[brms]{brmsprior}} stored in a
#' \code{\link[brms]{brmsfit}}.
#'
#' @details \pkg{brms} stores more than was supplied: a duplicated
#' \code{coef = "Intercept"} row for each population-level prior, and its own
#' defaults for the dispersion parameter. Passed back as a \code{prior}
#' argument, the extra rows make \code{make_inits()} reject the set. Only rows
#' with \code{source == "user"} are kept.
#'
#' \pkg{brms} records an absent bound as \code{""}, where
#' \code{define_prior()} uses \code{NA}. The result uses \code{NA}, so that it
#' compares equal to a generated prior.
#'
#' @return An object of class \code{\link[brms]{brmsprior}}.
#'
#' @noRd
usable_prior <- function(prior) {
  if (is.null(prior) || nrow(prior) == 0) {
    return(prior)
  }
  # Keep class "b", which holds the curve's parameters and those of a
  # variance-function disp() term, and the auxiliary classes, so that a user
  # prior on any of them round trips. A prior brms chose itself is dropped.
  keep <- prior$source == "user" & prior$coef == "" &
    (prior$class == "b" | prior$class %in% auxiliary_classes())
  out <- prior[keep, , drop = FALSE]
  for (bound in c("lb", "ub")) {
    if (bound %in% names(out)) {
      out[[bound]][!nzchar(out[[bound]])] <- NA_character_
    }
  }
  rownames(out) <- NULL
  out
}

#' Classes brms uses for a family parameter that is not part of the mean curve
#'
#' Dispersion classes (\code{sigma}, \code{shape}, \code{phi}), the mixing
#' probabilities \code{zi} and \code{hu}, and \code{sd}, a group-level
#' standard deviation. \code{usable_prior()} keeps a user prior on any of
#' them, and none takes an initial value from the curve's own search.
#'
#' \code{zi} has a class of its own only for \code{zero_inflated_poisson} and
#' \code{zero_inflated_negbinomial}, which are fitted as a single block. The
#' hurdle families and \code{zero_inflated_beta} are fitted as two blocks, and
#' the second block's priors are class \code{"b"} with a prefixed
#' \code{nlpar}, so these names match nothing generated for them.
#'
#' @return A \code{\link[base]{character}} vector.
#'
#' @noRd
auxiliary_classes <- function() {
  # "sd" is listed because bayesnec generates a prior for a group-level
  # standard deviation, and get_priors() must report it.
  c("sigma", "shape", "phi", "zi", "hu", "sd")
}
